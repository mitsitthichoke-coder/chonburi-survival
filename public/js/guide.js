// แปลง Markdown อย่างง่าย (หัวข้อ ตาราง รายการ ตัวหนา โค้ด) เป็น HTML
const esc = (t) => String(t).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const inline = (t) => esc(t).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/`(.+?)`/g, '<code>$1</code>');
export function mdToHtml(md) {
  const out = [], lines = md.split('\n'); let i = 0;
  while (i < lines.length) {
    const L = lines[i];
    if (L.startsWith('### ')) { out.push(`<h4>${inline(L.slice(4))}</h4>`); i++; continue; }
    if (L.startsWith('|')) {
      const rows = []; while (i < lines.length && lines[i].startsWith('|')) { if (!/^\|[-| ]+\|$/.test(lines[i])) rows.push(lines[i].slice(1, -1).split('|').map((c) => c.trim())); i++; }
      out.push(`<table class="gtab">${rows.map((r, j) => `<tr>${r.map((c) => (j ? `<td>${inline(c)}</td>` : `<th>${inline(c)}</th>`)).join('')}</tr>`).join('')}</table>`); continue;
    }
    if (/^\s*(- |\d+\. )/.test(L)) {
      const ord = /^\d+\. /.test(L.trim()), items = []; while (i < lines.length && /^\s*(- |\d+\. )/.test(lines[i])) { items.push(lines[i].replace(/^\s*(- |\d+\. )/, '')); i++; }
      out.push(`<${ord ? 'ol' : 'ul'}>${items.map((x) => `<li>${inline(x)}</li>`).join('')}</${ord ? 'ol' : 'ul'}>`); continue;
    }
    if (L.trim()) out.push(`<p>${inline(L)}</p>`);
    i++;
  }
  return out.join('');
}
